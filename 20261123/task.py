#案例一 垃圾分类
# 垃圾分类可以减少对环境的污染，请根据垃圾属性分为可回收垃圾、厨余垃圾、有害垃圾和其他垃圾
# 可回收垃圾：废纸、塑料瓶、易拉罐、金属元件、玻璃瓶、废旧衣物、旧数码产品、旧家电
# 厨余垃圾：食材废料、瓜果蔬菜、蛋壳、鱼骨、过期食品
# 有害垃圾：废电池、废灯管、消毒棉棒、油漆、杀虫剂
# 其他垃圾：餐巾纸、保鲜膜、砖瓦灰土
# 小明周末结束聚餐后，需要将废纸、塑料瓶、食材废料、瓜果蔬菜、餐巾纸等垃圾投入垃圾桶
# 请编写程序帮他完成垃圾分类工作



waste_list = ['废纸', '塑料瓶', '食材废料', '瓜果蔬菜', '餐巾纸']
recy_waste = ('废纸', '塑料瓶', '易拉罐', '金属元件', '玻璃瓶', '废旧衣物', '旧数码产品', '旧家电')
kit_waste = ('食材废料', '瓜果蔬菜', '蛋壳', '鱼骨', '过期食品')
harm_waste = ('废电池', '废灯管', '消毒棉棒', '油漆', '杀虫剂')
other_waste = ('餐巾纸', '保鲜膜', '砖瓦灰土')

for waste in waste_list:
    if waste in recy_waste:
        print(waste, '是可回收垃圾')
    elif waste in kit_waste:
        print(waste, '是厨余垃圾')
    elif waste in harm_waste:
        print(waste, '是有害垃圾')
    else:
        print(waste, '是其他垃圾')