#3、删除 del pop remove
a = [1, 2, 3, "中文", "one", 4, 5, 6, 7, 8]
# 1）del语句：删除指定索引位置的元素
#del 列表名[索引位置]
del a[3]
print(a)

# 2）pop()方法：删除指定索引位置的元素，并可以对删除的元素输出
#列表名.pop(索引位置)
b = [1, 2, 3, "中文", "one", 4, 5, 6, 7, 8]
print(b.pop(3))
print(b)

# 3）remove()方法：删除指定的元素，删除第一个匹配的元素
#列表名.remove(元素)
c = [1, 2, 3, "中文", "one", 4, 5, 6, 7, 8]
c.remove("中文")
print(c)