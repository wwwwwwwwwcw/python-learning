#创建一个列表，其元素包括cat、dog、10、20、hat、mice，并对其进行以下操作：
# 1）增加一个“pear”元素
# 2）删除列表第二个元素
# 3）修改列表中的数值变为原有的数值的两倍
# 4）查询mice在列表中的第几位
# 5）输出查询完的列表个数
# 6）输出执行完上述操作后的列表
a = ["cat", "dog", 10, 20, "hat", "mice"]
# 1）增加一个“pear”元素
a.append("pear")
# 2）删除列表第二个元素
del a[1]
# 3）修改列表中的数值变为原有的数值的两倍
a[1] = a[1] * 2
a[2] = a[2] * 2
# 4）查询mice在列表中的第几位
print(a.index("mice"))
# 5）输出查询完的列表个数
print(len(a))
# 6）输出执行完上述操作后的列表
print(a)