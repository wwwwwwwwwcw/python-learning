# 列表案例一 成语接龙
# 成语接龙游戏规则：1、成语必须是4个字组成
# 2、除了第一个成语外，其余成语的第一个字都是上一个成语的最后一个字
# 现有一组成语：万事如意，发奋图强，笑容满面，意气风发，强颜欢笑
# 本任务要求编写程序，以万事如意为第一个成语，完成其余成语的自动接龙
a='万事如意'
end_str=a[-1]
new_li=[a]
li=['发愤图强','笑容满面','意气风发','强颜欢笑']
for b in range(len(li)):
    for i in li:
        if end_str==i[0]:
            new_li.append(i)
            li.remove(i)
            end_str=i[-1]
print(new_li)