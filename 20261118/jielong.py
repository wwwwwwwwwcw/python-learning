成语列表 = ["万事如意", "发奋图强", "笑容满面", "意气风发", "强颜欢笑"]
接龙成语 = [成语列表[0]]
剩余成语 = 成语列表[1:]          # 切片本身就产生新列表，不需要 copy()

while True:
    当前尾字 = 接龙成语[-1][-1]
    找到了 = False
    for 成语 in 剩余成语:
        if 成语[0] == 当前尾字:
            接龙成语.append(成语)
            剩余成语.remove(成语)
            找到了 = True
            break
    if not 找到了:
        break

print(接龙成语)