# 4、有100元，买100只鸡，其中公鸡5元一只，母鸡3元一只，小鸡1元三只，有多少种买法？
count = 0
for 喔喔喔 in range(0, 21):
    for 咯咯哒 in range(0, 34):
        叽叽叽 = 100 - 喔喔喔 - 咯咯哒
        if 叽叽叽 >= 0 and 叽叽叽 % 3 == 0 and 喔喔喔*5 + 咯咯哒*3 + 叽叽叽//3 == 100:
            print("公鸡", 喔喔喔, "母鸡", 咯咯哒, "小鸡", 叽叽叽)
            count += 1
print("共", count, "种买法")