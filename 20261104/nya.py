# 1、计算1-1000以内所有的水仙花数（153=1^3+5^3+3^3）
for 水仙 in range(100,1000):
    超 = 水仙 // 100
    可 = 水仙 //10 % 10
    爱 = 水仙 % 10
    if 超 ** 3 + 可 ** 3 + 爱 ** 3 == 水仙:
        print(水仙)


# 2、求1000以内能同时被3和7整除的数
for chao in range(1,1001):
    if chao % 3 == 0 and chao % 7 == 0:
        print(chao)

