# 1、计算1-1000以内所有的水仙花数（153=1^3+5^3+3^3）
for i in range(100, 1000):
    a = i // 100
    b = (i // 10) % 10
    c = i % 10
    if a ** 3 + b ** 3 + c ** 3 == i:
        print(i)

# 2、求1000以内能同时被3和7整除的数
for i in range(1, 1001):
    if i % 3 == 0 and i % 7 == 0:
        print(i)

# 3、将一张面值为1000的人民币换成等值10、5、1元零钱有哪些组合？
for i in range(0, 101):
    for j in range(0, 201):
        for k in range(0, 1001):
            if 10 * i + 5 * j + k == 1000:
                print("10元: ", i, "张, 5元: ", j, "张, 1元: ", k, "张")

# 4、有100元，买100只鸡，其中公鸡5元一只，母鸡3元一只，小鸡1元三只，有多少种买法？
for x in range(0, 21):
    for y in range(0, 34):
        z = 100 - x - y
        if z >= 0 and (5 * x + 3 * y + z / 3) == 100:
            print("公鸡: ", x, "只, 母鸡: ", y, "只, 小鸡: ", z, "只")