#逢5起立游戏————几个同学围一圈玩游戏，从1开始数数，当数到5或者数字是以5结尾或者是5的倍数就需要起立而不说出这个数，编写程序，计算从1到100中有多少个数字需要起立多少次
count = 0
for i in range(1, 101):
    if i % 5 == 0 or i % 10 == 5:
        print(i, "起立")
        count += 1
print("总共需要起立", count, "次")

# 一辆车以固定的速度行驶，司机在上午10点整看里程表是一个对称数，95859
# 两个小时后，出现了一个新的对称数，仍然是一个五位数，问，车速是多少？新的里程数是多少
s = 95859

for n in range(s + 1, 100000):
    o = n
    r = 0
    temp = n
    while temp > 0:
        r = r * 10 + temp % 10
        temp = temp // 10
    if o == r:
        p = o
        break

d = p - s
v = d / 2

print("新里程数:", p)
print("距离:", d, "公里")
print("速度:", v, "公里/小时")